### Part 3: Prepare Conflict Data ###
conflicts <- read_csv("./data/raw/conflict.csv")
head(conflicts)

# Derive binary armed conflict variable
# Recall from paper: definition of armed conflict -> 25+ cummulative deaths 
# from all conflicts within same calendar-conflict year
conflicts_clean <- conflicts |> 
  group_by(iso, year, conflict_id) |>
  summarize(event_deaths = sum(best, na.rm=TRUE), .groups = "drop") |>
  group_by(iso, year) |>
  summarize(had_conflict = as.integer(any(event_deaths >= 25, na.rm=TRUE)), .groups = "drop") |>
  mutate(
    year = year + 1
  )

### Part 4: Merge all data into final DF ###
covariates <- read.csv("./data/raw/covariates.csv", header = TRUE)

data_list <- list(wbdata, disasters_clean, conflicts_clean, covariates)
final_data <- reduce(data_list, full_join, by = c('iso', 'year'))

# Deal with missingness in earthquake, drought, and had_conflict columns; if no recorded disaster for that year,
# then both columns will be set to 0 instead of NA
final_data <- final_data |> 
  mutate(
    earthquake = replace_na(earthquake, 0),
    drought = replace_na(drought, 0),
    had_conflict = replace_na(had_conflict, 0)
  )

head(final_data)

# Write final csv to data/processed folder
write_csv(
  final_data, 
  "./data/processed/final_data.csv",
  na = "NA"
