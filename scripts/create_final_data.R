### Part 1: Prepare World Bank Data ###

manip_wb <- function(df, varname){
  df_long <- df |> 
    pivot_longer(cols = starts_with("X"),
                 names_to = "year",
                 names_prefix = "X", # removes X from year column
                 values_to = varname) |> 
    mutate(year = as.numeric(year)) |> # change year to numeric
    dplyr::select(iso, year, varname)
}

matmor <- manip_wb(df = matmor0, varname = "matmor")
infmor <- manip_wb(df = infmor0, varname = "infmor")
neomor <- manip_wb(df = neomor0, varname = "neomor")
un5mor <- manip_wb(df = un5mor0, varname = "un5mor")

# Put all data frames into list and merge via iso & year cols
wblist <- list(matmor, infmor, neomor, un5mor)
wbdata <- wblist |> 
  reduce(full_join, by = c('iso', 'year'))


### Part 2: Prepare Disaster Data ###
# Read CSV file, clean col names
disasters <- read_csv("./data/raw/disaster.csv")
disasters <- clean_names(disasters)

# Filter df by 2000 <= year <= 2019, disaster_type in ["Earthquake", "Drought"]
disasters_clean <- disasters |> filter(
    year <= 2019 &
    year >= 2000 &
    disaster_type %in% c("Earthquake", "Drought")
  ) |>
  select(year, iso, disaster_type) |>
  mutate(
    drought = as.integer(disaster_type == "Drought"),
    earthquake = as.integer(disaster_type == "Earthquake")
  ) |>
  select(year, iso, drought, earthquake) |>
  group_by(year, iso) |>
  summarize(across(c(drought, earthquake), max))

